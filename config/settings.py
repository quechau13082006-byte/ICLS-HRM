def _doc_file_env(duong_dan):
    """Đọc file .env (mỗi dòng KHOA=gia_tri, dòng bắt đầu bằng # là ghi chú) vào biến môi trường.

    File .env chứa mật khẩu ứng dụng Gmail nên KHÔNG đưa lên git (đã có trong .gitignore); mẫu xem .env.example.
    Không cài thêm thư viện: tự đọc từng dòng. Biến môi trường đã đặt sẵn thì giữ nguyên.
    """
    if not duong_dan.exists():
        return
    for dong in duong_dan.read_text(encoding='utf-8').splitlines():
        dong = dong.strip()
        if dong and not dong.startswith('#') and '=' in dong:
            khoa, gia_tri = dong.split('=', 1)
            os.environ.setdefault(khoa.strip(), gia_tri.strip().strip('"').strip("'"))


_doc_file_env(BASE_DIR / '.env')


